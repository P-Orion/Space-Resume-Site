#!/usr/bin/env node
/**
 * gen-sitemap.mjs — rebuilds the MECHANICAL, derivable facts about the site
 * straight from source, so those facts can never go stale.
 *
 * Run:  node docs/gen-sitemap.mjs
 * Out:  docs/SITE-MAP.generated.md   (DO NOT hand-edit; regenerate instead)
 *
 * It derives: section map (ids + screen labels + line numbers), nav order,
 * the skills marquee list, asset inventory, line count, and a content hash.
 * Everything here is extracted from the real files — if the site changes and
 * this is re-run, the output tracks it. Prose/judgment lives in SITE-GUIDE.md.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, join, relative } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const siteDir = join(root, "Home page animation redesign", "github-export");
const htmlPath = join(siteDir, "index.html");
const outPath = join(here, "SITE-MAP.generated.md");

const html = readFileSync(htmlPath, "utf8");
const lines = html.split(/\r?\n/);

// --- section map: every element carrying data-screen-label, with its id + line ---
const sections = [];
lines.forEach((line, i) => {
  const label = line.match(/data-screen-label="([^"]+)"/);
  if (!label) return;
  const id = line.match(/id="([^"]+)"/);
  sections.push({ line: i + 1, id: id ? id[1] : "—", label: label[1] });
});

// --- nav order: the data-nav links in the top bar ---
const navOrder = [];
for (const m of html.matchAll(/data-nav="([^"]+)"[^>]*>([^<]+)</g)) {
  navOrder.push({ target: m[1], text: m[2].trim() });
}

// --- skills marquee: const names = [ ... ] inside the script block ---
let skills = [];
const skillsMatch = html.match(/const names\s*=\s*\[([^\]]*)\]/);
if (skillsMatch) {
  skills = skillsMatch[1]
    .split(",")
    .map((s) => s.replace(/['"`]/g, "").trim())
    .filter(Boolean);
}

// --- editor props exposed on the data-dc-script tag ---
let props = [];
const propsMatch = html.match(/data-props="([^"]+)"/);
if (propsMatch) {
  try {
    const decoded = propsMatch[1].replace(/&quot;/g, '"');
    const obj = JSON.parse(decoded);
    props = Object.entries(obj).map(([k, v]) => ({
      name: k,
      type: v.editor ?? v.tsType ?? "?",
      default: v.default,
    }));
  } catch { /* leave empty if the shape changes */ }
}

// --- assets on disk ---
function listDir(sub) {
  try {
    return readdirSync(join(siteDir, sub))
      .filter((f) => !f.startsWith("."))
      .sort();
  } catch {
    return [];
  }
}
const images = listDir("images");
const documents = listDir("documents");

// --- file facts ---
const hash = createHash("sha256").update(html).digest("hex").slice(0, 12);
const mtime = statSync(htmlPath).mtime.toISOString().slice(0, 10);
const today = new Date().toISOString().slice(0, 10);
const rel = (p) => relative(root, p).replace(/\\/g, "/");

// --- render markdown ---
const table = (rows) => rows.join("\n");
const out = `# Site Map (generated — do not edit)

> **Auto-generated by [\`docs/gen-sitemap.mjs\`](gen-sitemap.mjs). Do not hand-edit.**
> Regenerate with \`node docs/gen-sitemap.mjs\`. These are the mechanical facts derived
> straight from source, so they cannot drift. Narrative/judgment lives in
> [\`SITE-GUIDE.md\`](SITE-GUIDE.md).

- **Generated:** ${today}
- **Source:** \`${rel(htmlPath)}\`
- **Lines:** ${lines.length}   ·   **Last modified:** ${mtime}   ·   **Content hash:** \`${hash}\`

## Sections (by \`data-screen-label\`)

| Line | id | Screen label |
|-----:|----|--------------|
${table(sections.map((s) => `| ${s.line} | \`${s.id}\` | ${s.label} |`))}

## Nav order (top bar)

${navOrder.length ? navOrder.map((n, i) => `${i + 1}. ${n.text} → \`#${n.target}\``).join("\n") : "_none found_"}

## Skills marquee (${skills.length})

${skills.length ? skills.join(" · ") : "_not found_"}

## Editor props (\`data-props\`)

${props.length ? `| Prop | Type | Default |\n|------|------|---------|\n${props.map((p) => `| \`${p.name}\` | ${p.type} | ${JSON.stringify(p.default)} |`).join("\n")}` : "_none found_"}

## Assets

**images/** (${images.length}): ${images.length ? images.map((f) => `\`${f}\``).join(", ") : "_none_"}

**documents/** (${documents.length}): ${documents.length ? documents.map((f) => `\`${f}\``).join(", ") : "_none_"}
`;

writeFileSync(outPath, out);
console.log(`Wrote ${rel(outPath)} — ${sections.length} sections, ${skills.length} skills, ${images.length + documents.length} assets, hash ${hash}`);
